const EXTRA: RizzLine[] = Object.entries(EXTRA_LINES).flatMap(([categoryId, texts]) =>
  texts.map((text, index) => ({
    id: `${categoryId}-${(EXTRA_START_INDEX[categoryId] || 1) + index}`,
    categoryId,
    text,
  }))
);

export const RIZZ_LINES: RizzLine[] = [...CORE_LINES, ...EXTRA];

export const getCategory = (id: string): RizzCategory | undefined =>
  CATEGORIES.find((category) => category.id === id);

// AI-generated lines live for the session only. They are registered here so the
// Saved tab resolves them through the exact same getLine() lookup as the rest.
const extraLines: RizzLine[] = [];

export const registerLine = (line: RizzLine) => {
  if (!extraLines.some((item) => item.id === line.id)) extraLines.push(line);
};

export const getLine = (id: string): RizzLine | undefined =>
  RIZZ_LINES.find((line) => line.id === id) || extraLines.find((line) => line.id === id);

export const linesForCategory = (categoryId: string): RizzLine[] =>
  categoryId === ALL_CATEGORY_ID
    ? RIZZ_LINES
    : RIZZ_LINES.filter((line) => line.categoryId === categoryId);

export const randomLineFor = (categoryId: string): RizzLine =>
  linesForCategory(categoryId)[Math.floor(Math.random() * linesForCategory(categoryId).length)] ||
  RIZZ_LINES[0];
